r"""
freeze_requirements.py - write the EXACT versions of everything installed in
this project's .venv to requirements.txt.

Run from the project root, with the project's own Python:
    .venv\Scripts\python.exe python\freeze_requirements.py

requirements.in lists what you want (loose); requirements.txt records what you
have (exact). Rebuilding a project installs requirements.txt, so the same
versions come back every time, until you choose to update.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

if sys.prefix == sys.base_prefix:
    sys.exit("Not running inside a virtual environment: use .venv\\Scripts\\python.exe "
             "(otherwise this would freeze every package of your global Python).")

frozen = subprocess.run([sys.executable, "-m", "pip", "freeze"],
                        check=True, capture_output=True, text=True).stdout
header = ("# AUTO-GENERATED by python/freeze_requirements.py (exact versions of everything installed).\n"
          "# Do not edit by hand: edit requirements.in, then update or re-freeze.\n")
(ROOT / "requirements.txt").write_text(header + frozen, encoding="utf-8", newline="\n")
print(f"requirements.txt written: {len(frozen.splitlines())} packages")
