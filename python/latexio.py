"""
latexio.py - small helpers that hand Python results over to LaTeX.

Everything is written into `latex/generated/` (project root / latex / generated):

    write_macros()                -> latex/generated/numbers.tex   (\\newcommand{\\name}{value})
    write_table()                 -> latex/generated/<name>.tex    (booktabs tabular)
    new_figure() + save_figure()  -> latex/generated/<name>.pdf    (vector plot)

Plot fonts follow the paper automatically: if main.tex contains an active
`\\timestrue` line the plots use Times, otherwise Computer Modern.

This file is generic: you normally never edit it. Your own calculations go in
compute.py.
"""
from __future__ import annotations

import numbers
import re
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent.parent      # project root (python/ is one level down)
GEN = ROOT / "latex" / "generated"

# ---------------------------------------------------------------------------
# Page geometry in inches. KEEP IN SYNC with header.tex
# (a4paper, left/right margins 1.9 cm, columnsep 0.7 cm).
# ---------------------------------------------------------------------------
_CM = 1 / 2.54
TEXT_WIDTH = (21.0 - 2 * 1.9) * _CM                 # full page width of text
COLUMN_WIDTH = (21.0 - 2 * 1.9 - 0.7) / 2 * _CM     # one column


# ---------------------------------------------------------------------------
# Number formatting
# ---------------------------------------------------------------------------
def fmt(x, sig: int = 3) -> str:
    """Number -> LaTeX string (no $ signs).

    Plain notation for 1e-3 <= |x| < 1e4, scientific notation otherwise:
        67.4  ->  67.4        1.2345e-5  ->  1.23\\times10^{-5}
    Integers are printed as they are.
    """
    if isinstance(x, numbers.Integral):
        return str(int(x))
    x = float(x)
    if x == 0:
        return "0"
    if 1e-3 <= abs(x) < 1e4:
        s = f"{x:.{sig}g}"
        if "e" not in s:
            return s
    mantissa, exponent = f"{x:.{sig - 1}e}".split("e")
    return rf"{mantissa}\times10^{{{int(exponent)}}}"


# ---------------------------------------------------------------------------
# Numbers in the running text
# ---------------------------------------------------------------------------
def write_macros(values: dict, filename: str = "numbers.tex", sig: int = 3) -> Path:
    """Write one \\newcommand per entry, e.g. {"Hzero": 67.4} -> \\Hzero.

    * Macro names may contain letters only (a LaTeX rule: no digits, no _).
    * Numbers are formatted with fmt() and wrapped in \\ensuremath, so they
      work both in text and in math mode.
    * Strings are written verbatim (raw LaTeX).
    """
    GEN.mkdir(exist_ok=True)
    lines = ["% AUTO-GENERATED by compute.py - do not edit by hand"]
    for name, val in values.items():
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(
                f"Macro name {name!r} is not valid: use letters only "
                "(no digits, underscores or spaces), e.g. 'Hzero' not 'H0'."
            )
        body = val if isinstance(val, str) else rf"\ensuremath{{{fmt(val, sig)}}}"
        lines.append(rf"\newcommand{{\{name}}}{{{body}}}")
    path = GEN / filename
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# Tables
# ---------------------------------------------------------------------------
def write_table(filename: str, header: list, rows: list, align: str | None = None,
                sig: int = 3) -> Path:
    """Write a booktabs `tabular` to generated/<filename>.

    header : list of column titles (LaTeX allowed, e.g. r"$\\ell$")
    rows   : list of rows; numbers are formatted and put in math mode,
             strings are written as they are.
    Use it in main.tex inside a table float:  \\input{latex/generated/<filename>}
    """
    GEN.mkdir(exist_ok=True)
    align = align or "l" + "c" * (len(header) - 1)

    def cell(v):
        return v if isinstance(v, str) else f"${fmt(v, sig)}$"

    lines = [
        "% AUTO-GENERATED by compute.py - do not edit by hand",
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(cell(v) for v in row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    path = GEN / filename
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# Figures
# ---------------------------------------------------------------------------
def paper_font(main_tex: Path = ROOT / "main.tex") -> str:
    """'times' if main.tex has an active \\timestrue line, else 'cm'."""
    try:
        src = main_tex.read_text(encoding="utf-8")
    except OSError:
        return "cm"
    return "times" if re.search(r"^[^%\n]*\\timestrue", src, re.M) else "cm"


def set_plot_style(font: str = "auto", size: float = 8.0) -> str:
    """Make matplotlib text use the same fonts as the paper (via your TeX Live).

    font : "auto" (follow main.tex), "times" or "cm".
    Returns the font actually used.
    """
    if font == "auto":
        font = paper_font()
    rc = {
        "text.usetex": True,
        "font.family": "serif",
        "font.size": size,
        "axes.labelsize": size,
        "legend.fontsize": size - 1,
        "xtick.labelsize": size - 1,
        "ytick.labelsize": size - 1,
        "axes.linewidth": 0.6,
        "lines.linewidth": 1.0,
    }
    if font == "times":
        rc["font.serif"] = ["Times"]
        rc["text.latex.preamble"] = r"\usepackage{mathptmx}"
    else:
        rc["font.serif"] = ["Computer Modern Roman"]
        rc["mathtext.fontset"] = "cm"
    mpl.rcParams.update(rc)
    return font


def new_figure(width: str | float = "column", aspect: float = 0.75, **subplots_kw):
    """Create fig, ax with exactly the width of a column ("column"), of the
    full text width ("full", for figure* environments) or a width in inches."""
    w = {"column": COLUMN_WIDTH, "full": TEXT_WIDTH}.get(width, width)
    return plt.subplots(figsize=(w, w * aspect), layout="constrained", **subplots_kw)


def save_figure(fig, name: str) -> Path:
    """Save as vector PDF in latex/generated/<name>.pdf and close the figure."""
    GEN.mkdir(exist_ok=True)
    path = GEN / f"{name}.pdf"
    fig.savefig(path)
    plt.close(fig)
    return path
